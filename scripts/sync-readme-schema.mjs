#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs'

const TARGET = 'README.md'
const SOURCE = 'doc/schema/README.md'
const MARKER = '> Generated by [tbls](https://github.com/k1LoW/tbls)'

const source = readFileSync(SOURCE, 'utf8')

const section = (name) => {
  const part = source
    .split(/^## /m)
    .find((candidate) => candidate.startsWith(`${name}\n`))
  if (!part) throw new Error(`Missing "${name}" section in ${SOURCE}`)
  return part.slice(name.length + 1).trim()
}

const tables = section('Tables').replace(/\[(public\.[^\]]+)\]\([^)]+\)/g, '$1')
const functions = section('Stored procedures and functions')
const enums = section('Enums')
  .split('\n')
  .filter((line) => !/^\| (auth|net|storage|graphql|realtime|vault)\./.test(line))
  .join('\n')
const relations = section('Relations')
  .replace(/\n---\n\n> Generated by[\s\S]*$/, '')
  .trimEnd()

const block = `### Database

The schema below is generated with [\`tbls\`](https://github.com/k1LoW/tbls) from
the running local Supabase database. Regenerate it with \`pnpm docs:schema\` (see
[Regenerating the schema docs](#regenerating-the-schema-docs)).

#### Tables

${tables}

#### Stored procedures and functions

${functions}

#### Enums

${enums}

#### Relations

${relations}

${MARKER}`

const readme = readFileSync(TARGET, 'utf8')
const start = readme.indexOf('### Database')
const markerAt = readme.indexOf(MARKER, start)

if (start === -1 || markerAt === -1) {
  throw new Error(`Could not locate the generated Database block in ${TARGET}`)
}

const end = markerAt + MARKER.length
writeFileSync(TARGET, readme.slice(0, start) + block + readme.slice(end))
console.log(`${TARGET}: Database section synced from ${SOURCE}`)
