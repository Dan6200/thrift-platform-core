#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'

const TARGET = 'packages/thrift-api/docs/schema.md'
const SOURCE = 'doc/schema/README.md'
const MARKER = '> Generated by [tbls](https://github.com/k1LoW/tbls)'

const source = readFileSync(SOURCE, 'utf8')

const section = (name) => {
  const part = source
    .split(/^## /m)
    .find((candidate) => candidate.startsWith(`${name}\n`))
  if (!part) throw new Error(`Missing "${name}" section in ${SOURCE}`)
  return part.slice(name.length + 1).trim()
}

const tables = section('Tables').replace(/\[(public\.[^\]]+)\]\([^)]+\)/g, '$1')
const functions = section('Stored procedures and functions')
const enums = section('Enums')
  .split('\n')
  .filter((line) => !/^\| (auth|net|storage|graphql|realtime|vault)\./.test(line))
  .join('\n')
const relations = section('Relations')
  .replace(/\n---\n\n> Generated by[\s\S]*$/, '')
  .trimEnd()

const doc = `# Thrift API — Database schema

This reference is generated with [\`tbls\`](https://github.com/k1LoW/tbls) from
the running local Supabase database. Do not hand-edit it; run \`pnpm docs:schema\`
from the repo root after changing the schema.

## Tables

${tables}

## Stored procedures and functions

${functions}

## Enums

${enums}

## Relations

${relations}

${MARKER}

## Regenerating

\`\`\`bash
# Requires tbls: https://github.com/k1LoW/tbls#install
supabase start            # from packages/thrift-api
pnpm docs:schema          # from the repo root
\`\`\`

The per-table markdown lands in \`doc/schema/\` (ignored by git); this file is the
tracked, curated view. If the database is not on the default local port, set
\`SUPABASE_DB_URL\` to the connection string \`tbls\` should read.
`

mkdirSync(dirname(TARGET), { recursive: true })
writeFileSync(TARGET, doc)
console.log(`${TARGET}: generated from ${SOURCE}`)
